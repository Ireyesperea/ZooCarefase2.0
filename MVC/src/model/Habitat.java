package model;

import java.util.ArrayList;
/**
 * A habitat of the zoo. It keeps its responsible staff and its assigned animals.
 */
public class Habitat {
   private final String code;
   private String name;
   private EnvironmentType environment;
   private double temperature;
   private double area;
   private double monthlyBudget;
   private int capacity;
   private HabitatStatus status;
   private ArrayList<Employee> staff;
   private ArrayList<Animal> animals;
/**
     * Creates a habitat without staff and without animals.
     *
     * <b>Pre:</b> the code is unique, the area and the capacity are greater than zero and the budget is not negative.<br>
     * <b>Post:</b> a habitat with the given data is created, with no staff and no animals.
     *
     * @param code unique code generated by the system
     * @param name name of the habitat, not empty
     * @param environment environment type, not null
     * @param temperature temperature in Celsius (can be negative)
     * @param area area in square meters, greater than zero
     * @param monthlyBudget monthly budget in COP, greater or equal to zero
     * @param capacity maximum number of animals, greater than zero
     * @param status initial status, not null
     */
   public Habitat(String code, String name, EnvironmentType environment,
                 double temperature, double area, double monthlyBudget, int capacity, HabitatStatus status) {
      this.code = code;
      this.name = name;
      this.environment = environment;
      this.temperature = temperature;
      this.area = area;
      this.monthlyBudget = monthlyBudget;
      this.capacity = capacity;
      this.status = status;
      this.staff = new ArrayList<>();
      this.animals = new ArrayList<>();
   }

    /**
     * Gets the code.
     *
     * <b>Pre:</b> the object has been created.<br>
     * <b>Post:</b> no data is modified.
     *
     * @return the unique code
     */
   public String getCode() {
      return this.code;
   }
/**
     * Gets the name.
     *
     * <b>Pre:</b> the object has been created.<br>
     * <b>Post:</b> no data is modified.
     *
     * @return the name of the habitat
     */
   public String getName() {
      return this.name;
   }
    /**
     * Changes the name.
     *
     * <b>Pre:</b> the new name is not empty.<br>
     * <b>Post:</b> the name is replaced by the new value.
     *
     * @param name the new name, not empty
     */

   public void setName(String name) {
      this.name = name;
   }
/**
     * Gets the environment.
     *
     * <b>Pre:</b> the object has been created.<br>
     * <b>Post:</b> no data is modified.
     *
     * @return the environment type
     */
   public EnvironmentType getEnvironment() {
      return this.environment;
   }
/**
     * Changes the environment.
     *
     * <b>Pre:</b> the new environment is not null.<br>
     * <b>Post:</b> the environment is replaced by the new value.
     *
     * @param environment the new environment, not null
     */
   public void setEnvironment(EnvironmentType environment) {
      this.environment = environment;
   }
    /**
     * Gets the temperature.
     *
     * <b>Pre:</b> the object has been created.<br>
     * <b>Post:</b> no data is modified.
     *
     * @return the temperature in Celsius
     */

   public double getTemperature() {
      return this.temperature;
   }
 /**
     * Changes the temperature.
     *
     * <b>Pre:</b> the new temperature is a valid number.<br>
     * <b>Post:</b> the temperature is replaced by the new value.
     *
     * @param temperature the new temperature in Celsius
     */
   public void setTemperature(double temperature) {
      this.temperature = temperature;
   }
 /**
     * Gets the area.
     *
     * <b>Pre:</b> the object has been created.<br>
     * <b>Post:</b> no data is modified.
     *
     * @return the area in square meters
     */
   public double getArea() {
      return this.area;
   }
/**
     * Changes the area.
     *
     * <b>Pre:</b> the new area is greater than zero.<br>
     * <b>Post:</b> the area is replaced by the new value.
     *
     * @param area the new area, greater than zero
     */
   public void setArea(double area) {
      this.area = area;
   }
  /**
     * Gets the monthly budget.
     *
     * <b>Pre:</b> the object has been created.<br>
     * <b>Post:</b> no data is modified.
     *
     * @return the budget in COP
     */
   public double getMonthlyBudget() {
      return this.monthlyBudget;
   }
 /**
     * Changes the monthly budget.
     *
     * <b>Pre:</b> the new budget is greater or equal to zero.<br>
     * <b>Post:</b> the monthly budget is replaced by the new value.
     *
     * @param monthlyBudget the new budget, greater or equal to zero
     */
   public void setMonthlyBudget(double monthlyBudget) {
      this.monthlyBudget = monthlyBudget;
   }
 /**
     * Gets the maximum capacity.
     *
     * <b>Pre:</b> the object has been created.<br>
     * <b>Post:</b> no data is modified.
     *
     * @return the maximum number of animals
     */
   public int getCapacity() {
      return this.capacity;
   }
/**
     * Changes the capacity.
     *
     * <b>Pre:</b> the new capacity is greater than zero.<br>
     * <b>Post:</b> the capacity is replaced by the new value.
     *
     * @param capacity the new capacity, greater than zero
     */
   public void setCapacity(int capacity) {
      this.capacity = capacity;
   }
 /**
     * Gets the status.
     *
     * <b>Pre:</b> the object has been created.<br>
     * <b>Post:</b> no data is modified.
     *
     * @return the current status
     */
   public HabitatStatus getStatus() {
      return this.status;
   }
 /**
     * Changes the status.
     *
     * <b>Pre:</b> the new status is not null.<br>
     * <b>Post:</b> the status is replaced by the new value.
     *
     * @param status the new status, not null
     */
   public void setStatus(HabitatStatus status) {
      this.status = status;
   }
/**
     * Gets the responsible staff.
     *
     * <b>Pre:</b> the habitat has been created.<br>
     * <b>Post:</b> the returned list is never null; no data is modified.
     *
     * @return the list of employees in charge (never null)
     */
   public ArrayList<Employee> getStaff() {
      return this.staff;
   }
/**
     * Replaces the responsible staff.
     *
     * <b>Pre:</b> the list is not null and every employee in it is active.<br>
     * <b>Post:</b> the staff list is replaced by the new one.
     *
     * @param staff the new list of employees, not null
     */
   public void setStaff(ArrayList<Employee> staff) {
      this.staff = staff;
   }
 /**
     * Gets the assigned animals.
     *
     * <b>Pre:</b> the habitat has been created.<br>
     * <b>Post:</b> the returned list is never null; no data is modified.
     *
     * @return the list of animals in this habitat (never null)
     */
   public ArrayList<Animal> getAnimals() {
      return this.animals;
   }
  /**
     * Gets the absolute occupation.
     *
     * <b>Pre:</b> the object has been created.<br>
     * <b>Post:</b> no data is modified.
     *
     * @return the number of animals assigned
     */
   public int getOccupancy() {
      return this.animals.size();
   }
 /**
     * Gets the occupation as a percentage.
     *
     * <b>Pre:</b> the object has been created.<br>
     * <b>Post:</b> no data is modified.
     *
     * @return the percentage between 0 and 100 (capacity is always greater than zero)
     */
   public double getOccupancyPercentage() {
      if (this.capacity <= 0) {
         return 0.0;
      }
      return (double) this.animals.size() * 100.0 / (double) this.capacity;
   }
/**
     * Tells if the habitat reached the occupancy alert level.
     *
     * <b>Pre:</b> the object has been created.<br>
     * <b>Post:</b> no data is modified.
     *
     * @return true if the occupation is 90% or more
     */
   public boolean isOccupancyAlert() {
      return this.getOccupancyPercentage() >= 90.0;
   }
 /**
     * Tells if there is room for one more animal.
     *
     * <b>Pre:</b> the object has been created.<br>
     * <b>Post:</b> no data is modified.
     *
     * @return true if the occupation is lower than the capacity
     */
   public boolean hasFreeSpace() {
      return this.animals.size() < this.capacity;
   }
 /**
     * Checks if an employee is responsible for this habitat.
     *
     * <b>Pre:</b> the employee is not null.<br>
     * <b>Post:</b> no data is modified.
     *
     * @param employee the employee to look for
     * @return true if the employee is in the staff list
     */
   public boolean hasStaffMember(Employee employee) {
      return this.staff != null && this.staff.contains(employee);
   }

    /**
     * Checks if an animal can live in this habitat according to its environment.
     * The medical environment (clinic) accepts any animal.
     *
     * <b>Pre:</b> the animal is not null.<br>
     * <b>Post:</b> no data is modified.
     *
     * @param animal the animal to check, not null
     * @return true if the environment is compatible
     */
   public boolean isCompatibleWith(Animal animal) {
      if (this.environment == EnvironmentType.MEDICAL) {
         return true;
      }
      return animal != null && this.environment == animal.getRequiredEnvironment();
   }
 /**
     * Adds an animal to the list and links it to this habitat.
     * <b>Pre:</b> the validations (status, capacity, compatibility) were already done.<br>
     * <b>Post:</b> the animal is in the list and its habitat is this one.
     *
     * @param animal the animal to add, not null
     */
   public boolean addAnimal(Animal animal) {
      if (animal == null || this.animals.contains(animal)) {
         return false;
      }
      this.animals.add(animal);
      animal.setHabitat(this);
      return true;
   }
/**
     * Removes an animal from the list and unlinks its habitat.
     * <b>Pre:</b> the animal is currently in this habitat.<br>
     * <b>Post:</b> the animal is not in the list and its habitat is null.
     *
     * @param animal the animal to remove, not null
     */
   public void removeAnimal(Animal animal) {
      if (animal == null) {
         return;
      }
      this.animals.remove(animal);
      animal.setHabitat(null);
   }
/**
     * Builds a text with the main data of the habitat.
     *
     * <b>Pre:</b> the object has been created.<br>
     * <b>Post:</b> no data is modified.
     *
     * @return a multi-line description
     */
   public String getDetails() {
      String details = "Code: " + this.code + "\nName: " + this.name + "\nEnvironment: " + String.valueOf(this.environment)
            + "\nTemperature: " + this.temperature + " C\nArea: " + this.area + " m2\nMonthly budget: "
            + String.format("%,.0f", this.monthlyBudget) + " COP\nCapacity: " + this.capacity + "\nStatus: "
            + String.valueOf(this.status) + "\nOccupancy: " + this.getOccupancy() + "/" + this.capacity
            + " (" + String.format("%.1f", this.getOccupancyPercentage()) + "%)\nResponsible staff: ";

      if (this.staff.isEmpty()) {
         details += "none";
      } else {
         for (int i = 0; i < this.staff.size(); i++) {
            details += this.staff.get(i).getFullName() + " (" + this.staff.get(i).getClass() + ")";
            if (i < this.staff.size() - 1) {
               details += ", ";
            }
         }
      }

      return details;
   }

   public String getAnimalList() {
    
    throw new UnsupportedOperationException("Unimplemented method 'getAnimalList'");
   }
}
